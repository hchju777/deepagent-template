"""concern 축 — **원인이 아니라 "먼저 물어볼 곳"이다.**

| | 먼저 묻는 것 | 왜 그게 제일 빠른가 |
|---|---|---|
| `system` | 인프라에게 — "파이프라인 살아 있나?" | Kafka lag·Redis TTL 만료·API 5xx는 증상 자체가 파이프라인 계층에 있다. 현장에 물어봐야 알 수 없다 |
| `operation` | 현장에게 — "라인 진짜 섰나요?" | 0/0/0은 우리 시스템은 신호를 주고 있고 **그 신호가 나쁜 것**이다. 현장 한 마디가 가설을 절반으로 자른다 |

## 원인을 담는 칸이 아니다 — 이건 오해하기 쉽다

0/0/0의 원인이 집계 **코드** 버그일 수 있다. 그래도 `operation`이다. 현장에
"라인 섰나요"를 먼저 묻는 것이 가설을 제일 빨리 자르기 때문이고, 어느 답이 와도
이득이기 때문이다:

    현장: "돌고 있는데요?"  →  집계 코드·데이터 유입 의심으로 넘어간다
    현장: "지금 섰어요"     →  끝. 조사할 게 없다

**원인은 `verdict_type`(12a)이 담는다.** 탐지 시점에는 원인을 알 수 없다 — 알면 조사가
필요 없다. 둘이 다른 것은 정상이고, `operation`으로 열려 `logic_bug`로 닫히는 케이스가
**이 시스템이 제일 값을 하는 경우다**(라인이 멈춘 것처럼 보였는데 실은 집계가 틀린 것).

## 기본값을 두지 않는다

원본 템플릿은 `concern: Concern = "system"`으로 기본값을 뒀고, 그 주석이 스스로 그것을
"분류가 아니라 **마이그레이션 비용에 대한 타협**"이라고 적었다 — 필수로 올리면 기존
픽스처 ~90곳을 고쳐야 했다는 것이다.

**우리는 그 비용이 0이다**(점검이 아직 없다). 그리고 기본값이 있으면 우리 첫 rule부터
오분류다 — 0/0/0은 `operation`인데 안 적으면 `system`으로 인프라팀에 간다.

## 값이 둘뿐인 이유

이벤트 어휘와 같다 — 둘로 표현 불가능한 것을 만나기 전엔 늘리지 않는다.
"""
from typing import Literal

Concern = Literal["system", "operation"]

# 런타임에 목록이 필요한 자리(config 키 검증 등)를 위한 짝.
# `typing.get_args`는 타입 내부 표현에 기대는 접근이라 파이썬 버전에 따라 흔들린다.
CONCERNS: tuple[str, ...] = ("system", "operation")
